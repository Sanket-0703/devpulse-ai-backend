-- Level 7: AI code reviews of pull requests, and their findings.

-- One run of the reviewer over one commit of a pull request.
CREATE TABLE reviews (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id    BIGINT       NOT NULL REFERENCES pull_requests (id) ON DELETE CASCADE,
    -- Who asked for it: daily limits and usage are per user.
    user_id            BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    head_sha           VARCHAR(64)  NOT NULL,
    status             VARCHAR(20)  NOT NULL
        CONSTRAINT reviews_status_check CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    provider           VARCHAR(40)  NOT NULL,
    model              VARCHAR(100) NOT NULL,
    files_reviewed     INT          NOT NULL DEFAULT 0,
    files_skipped      INT          NOT NULL DEFAULT 0,
    chunks             INT          NOT NULL DEFAULT 0,
    -- True if limits stopped the review before it covered everything.
    truncated          BOOLEAN      NOT NULL DEFAULT FALSE,
    prompt_tokens      INT          NOT NULL DEFAULT 0,
    completion_tokens  INT          NOT NULL DEFAULT 0,
    estimated_cost_usd NUMERIC(12, 6) NOT NULL DEFAULT 0,
    -- Open (not dismissed) findings per severity, kept up to date on dismiss.
    critical_count     INT          NOT NULL DEFAULT 0,
    high_count         INT          NOT NULL DEFAULT 0,
    medium_count       INT          NOT NULL DEFAULT 0,
    low_count          INT          NOT NULL DEFAULT 0,
    error              VARCHAR(500),
    started_at         TIMESTAMPTZ,
    finished_at        TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL,
    updated_at         TIMESTAMPTZ  NOT NULL
);

-- A pull request's review history, newest first.
CREATE INDEX idx_reviews_pull_request_created ON reviews (pull_request_id, created_at DESC);
-- A user's reviews (history page, today's usage).
CREATE INDEX idx_reviews_user_created ON reviews (user_id, created_at DESC);

-- At most one queued or running review per pull request. The database
-- enforces it, so two clicks at the same moment can't both start one.
CREATE UNIQUE INDEX uk_reviews_one_active_per_pull_request
    ON reviews (pull_request_id) WHERE status IN ('QUEUED', 'RUNNING');

-- One problem the reviewer found, on a line of the new version of a file
-- (or the whole file when line is null).
CREATE TABLE review_findings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id      BIGINT        NOT NULL REFERENCES reviews (id) ON DELETE CASCADE,
    source         VARCHAR(10)   NOT NULL
        CONSTRAINT review_findings_source_check CHECK (source IN ('AI', 'RULE')),
    -- For RULE findings: which security rule matched.
    rule_id        VARCHAR(60),
    severity       VARCHAR(10)   NOT NULL
        CONSTRAINT review_findings_severity_check CHECK (severity IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
    category       VARCHAR(20)   NOT NULL
        CONSTRAINT review_findings_category_check
            CHECK (category IN ('SECURITY', 'BUG', 'PERFORMANCE', 'MAINTAINABILITY', 'CODE_QUALITY')),
    title          VARCHAR(200)  NOT NULL,
    description    TEXT          NOT NULL,
    recommendation TEXT,
    file_path      VARCHAR(1000) NOT NULL,
    line           INT,
    dismissed      BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ   NOT NULL,
    updated_at     TIMESTAMPTZ   NOT NULL
);

CREATE INDEX idx_review_findings_review ON review_findings (review_id);
