-- Level 10: a semantic index of each repository's code (pgvector).

-- 1. Spring AI's generic table, created by the library at startup and only
--    used by a test endpoint. Code chunks get their own table below, owned by
--    Flyway like everything else (this was TODO M6-01).
DROP TABLE IF EXISTS vector_store;

-- 2. One piece of a source file, with its embedding.
CREATE TABLE code_chunks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT       NOT NULL REFERENCES github_repositories (id) ON DELETE CASCADE,
    path          VARCHAR(1000) NOT NULL,
    start_line    INT          NOT NULL,
    end_line      INT          NOT NULL,
    language      VARCHAR(30),
    content       TEXT         NOT NULL,
    -- SHA-256 of the text that was embedded: the key of the embedding cache.
    content_hash  CHAR(64)     NOT NULL,
    -- all-MiniLM-L6-v2 produces 384 numbers per text.
    embedding     vector(384)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Every search and every re-index is per repository.
CREATE INDEX idx_code_chunks_repository ON code_chunks (repository_id);

-- Approximate nearest-neighbour search by cosine distance (the <=> operator).
-- HNSW: a layered graph of nearby vectors; fast queries without scanning every row.
CREATE INDEX idx_code_chunks_embedding ON code_chunks USING hnsw (embedding vector_cosine_ops);

-- 3. Index state per repository (same lifecycle as the repository sync).
ALTER TABLE github_repositories
    ADD COLUMN index_status VARCHAR(20) NOT NULL DEFAULT 'NEVER'
        CONSTRAINT github_repositories_index_status_check
            CHECK (index_status IN ('NEVER', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    ADD COLUMN indexed_at TIMESTAMPTZ,
    -- The commit of the default branch that was indexed.
    ADD COLUMN indexed_commit_sha VARCHAR(64),
    ADD COLUMN indexed_files INT NOT NULL DEFAULT 0,
    ADD COLUMN indexed_chunks INT NOT NULL DEFAULT 0,
    ADD COLUMN index_error VARCHAR(500);

-- 4. How many related code snippets a review sent to the model as context.
ALTER TABLE reviews ADD COLUMN context_chunks INT NOT NULL DEFAULT 0;
