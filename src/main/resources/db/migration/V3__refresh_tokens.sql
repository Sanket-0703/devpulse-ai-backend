-- Refresh tokens for keeping users signed in (Level 2).
--
-- Only a SHA-256 hash of each token is stored, so a database leak does not
-- leak usable tokens. Every refresh rotates the token: the old row is
-- revoked and points at its replacement. All tokens descending from one
-- login share a family_id; if a revoked token is presented again (a sign
-- it was stolen), the whole family is revoked.

CREATE TABLE refresh_tokens (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash     VARCHAR(64)  NOT NULL UNIQUE,
    family_id      UUID         NOT NULL,
    expires_at     TIMESTAMPTZ  NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    revoked_at     TIMESTAMPTZ,
    replaced_by_id BIGINT       REFERENCES refresh_tokens (id) ON DELETE SET NULL
);

CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family_id ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);
