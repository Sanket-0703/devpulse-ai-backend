-- Level 9: GitHub webhooks, automatic reviews, publishing findings to GitHub.

-- 1. Every webhook delivery GitHub sent, once. The unique delivery id is the
--    duplicate protection: GitHub may deliver the same event twice (retries,
--    or "Redeliver" in the app settings), and the second insert fails.
CREATE TABLE webhook_deliveries (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id          VARCHAR(100) NOT NULL,
    event                VARCHAR(50)  NOT NULL,
    action               VARCHAR(50),
    installation_id      BIGINT,
    github_repository_id BIGINT,
    status               VARCHAR(20)  NOT NULL
        CONSTRAINT webhook_deliveries_status_check CHECK (status IN ('RECEIVED', 'PROCESSED', 'IGNORED', 'FAILED')),
    detail               VARCHAR(500),
    created_at           TIMESTAMPTZ  NOT NULL,
    updated_at           TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_webhook_deliveries_delivery_id UNIQUE (delivery_id)
);

-- A user sees the deliveries of their own installation, newest first.
CREATE INDEX idx_webhook_deliveries_installation_created ON webhook_deliveries (installation_id, created_at DESC);

-- 2. Review preferences, one row per user (created on first change; defaults otherwise).
CREATE TABLE review_settings (
    user_id               BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    -- Review automatically when a pull request opens or gets new commits.
    auto_review           BOOLEAN     NOT NULL DEFAULT TRUE,
    -- Post the findings of automatic reviews to GitHub without asking.
    auto_publish          BOOLEAN     NOT NULL DEFAULT FALSE,
    -- Findings below this severity stay in DevPulse.
    min_publish_severity  VARCHAR(10) NOT NULL DEFAULT 'MEDIUM'
        CONSTRAINT review_settings_severity_check CHECK (min_publish_severity IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
    created_at            TIMESTAMPTZ NOT NULL,
    updated_at            TIMESTAMPTZ NOT NULL
);

-- 3. How a review started, and whether (and where) it was published.
ALTER TABLE reviews
    ADD COLUMN triggered_by VARCHAR(10) NOT NULL DEFAULT 'MANUAL'
        CONSTRAINT reviews_triggered_by_check CHECK (triggered_by IN ('MANUAL', 'WEBHOOK')),
    ADD COLUMN published_at TIMESTAMPTZ,
    ADD COLUMN github_review_id BIGINT,
    ADD COLUMN github_review_url VARCHAR(1000),
    ADD COLUMN published_comments INT NOT NULL DEFAULT 0;
