-- Level 8: Playground runs ("paste code → review"). Only the numbers are
-- kept, for usage, cost and limits; the pasted code itself is never stored.
CREATE TABLE playground_runs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    language           VARCHAR(20)    NOT NULL,
    code_chars         INT            NOT NULL,
    findings           INT            NOT NULL,
    provider           VARCHAR(40)    NOT NULL,
    model              VARCHAR(100)   NOT NULL,
    prompt_tokens      INT            NOT NULL,
    completion_tokens  INT            NOT NULL,
    estimated_cost_usd NUMERIC(12, 6) NOT NULL,
    created_at         TIMESTAMPTZ    NOT NULL,
    updated_at         TIMESTAMPTZ    NOT NULL
);

-- Today's runs and cost per user.
CREATE INDEX idx_playground_runs_user_created ON playground_runs (user_id, created_at DESC);
